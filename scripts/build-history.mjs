// Builds js/history-data.js from the Ken French Fama/French 3 Factors file.
// 1) Download https://mba.tuck.dartmouth.edu/pages/faculty/ken.french/ftp/F-F_Research_Data_Factors_CSV.zip
// 2) Save the .zip or the unzipped .csv into data/
// 3) npm run data
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { parseFF, unzipFirst } from './ff-parse.mjs';

const dir = new URL('../data/', import.meta.url);
const file = readdirSync(dir).find(f => /F-F_Research_Data_Factors.*\.(csv|zip)$/i.test(f));
if (!file) { console.error('No F-F_Research_Data_Factors .csv or .zip found in data/'); process.exit(1); }
const buf = readFileSync(new URL(file, dir));
const text = /\.zip$/i.test(file) ? unzipFirst(buf) : buf.toString('latin1');
const { monthly, annual } = parseFF(text);
if (monthly.length < 1000 || annual.length < 90) { console.error(`Parsed too few rows (monthly ${monthly.length}, annual ${annual.length}). Is this the right file?`); process.exit(1); }
const out = `// Generated by scripts/build-history.mjs from ${file} (Ken French Data Library, Fama/French 3 Factors). Do not edit by hand.
// Values are percents. US market total return = mktrf + rf. Source: https://mba.tuck.dartmouth.edu/pages/faculty/ken.french/data_library.html
var FF_DATA = ${JSON.stringify({ source: 'Ken French Data Library, Fama/French 3 Factors', file, monthly, annual })};
`;
writeFileSync(new URL('../js/history-data.js', import.meta.url), out);
console.log(`Wrote js/history-data.js: ${monthly.length} months (${monthly[0].ym}–${monthly.at(-1).ym}), ${annual.length} years (${annual[0].y}–${annual.at(-1).y}).`);
